/*
 * The extension every internal name belongs to, and the ORDER each extension
 * lists its own -- both derived from php 8.5.9 (ReflectionExtension::getFunctions(),
 * getClassNames(), getConstants() and getINIEntries(), which answer in php's own
 * registration order rather than alphabetically) and restricted to the names this
 * engine actually registers. A name php has no row for is placed by hand: a language
 * construct or an engine-identity name belongs to Core, a library routine to the
 * family php keeps it in (or kept it in, for the ones php has since removed).
 *
 * Rows are GROUPED by extension and hold php's order within the group, which is what
 * get_extension_funcs() and ReflectionExtension::getFunctions() answer in. Nothing
 * here asserts a name EXISTS -- every reader filters against the live VM, so a build
 * without libxml, sqlite or curl answers the shorter list without a second table.
 */
